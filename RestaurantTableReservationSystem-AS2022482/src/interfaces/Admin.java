private final void totalTables(){
       int number = 1;
          
           try {                                                        
            String query = "SELECT * FROM tablemanager ";
            pst=conn.prepareStatement(query); 
            ResultSet rs=pst.executeQuery(query);        

            while (rs.next()) {
                if (number==rs.getInt("no")) {
                    lblTotalTableCount.setText(String.valueOf(rs.getInt("vipNormalTableCount")+rs.getInt("vipSpecialTableCount")
                     +rs.getInt("outdoorNormalTableCount")+rs.getInt("outdoorSpecialTableCount")+rs.getInt("firstFloorNormalTableCount")
                     +rs.getInt("firstFloorSpecialTableCount")));
                    
              }
            }
        }catch (Exception e) {
            System.out.println(e);
        } 
   }
