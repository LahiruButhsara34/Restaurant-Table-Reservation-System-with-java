    private void cmdSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmdSearchActionPerformed
        // TODO add your handling code here:
        String searchDate = null;
        
        Home view = new Home();
        view.tableCount();
  
        int timeNo=0 ;
        int bookedFinishedTablecount;
        int remainingTables;
       
       try{ 
       if (dataSearchCalender.getDate()==null) {
           JOptionPane.showMessageDialog(null, "Please Select a Date");
       }
       else{
           SimpleDateFormat sdf1 = new SimpleDateFormat("yyyy-MM-dd");
           searchDate = sdf1.format(dataSearchCalender.getDate());
       }
       
        if (cboTime.getSelectedItem()=="Select") {
            JOptionPane.showMessageDialog(null, "Please Select Time Slot");
          
        }
        else {
            timeNo = Integer.parseInt(lblTimeSlot.getText());
        }
        if (!optTableAselect.isSelected() && !optTableBselect.isSelected()) {
            JOptionPane.showMessageDialog(null, "Please Select Your Table Type");
        }
       else {
         if(timeNo!=0){
            if (optTableAselect.isSelected()) {
                String sql = "SELECT count(tableA) FROM customermanager WHERE date = ? AND timeSlotNo = ? AND tableA = ? ";
                pst = conn.prepareStatement(sql);
                pst.setString(1, searchDate);
                pst.setInt(2, timeNo);
                pst.setString(3, "y");
                ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    bookedFinishedTablecount = rs.getInt("count(tableA)");
                    if (bookedFinishedTablecount < view.countTableA) {
                        remainingTables = view.countTableA - bookedFinishedTablecount;

                        lblCurrentSituationTable.setText(String.valueOf(remainingTables) + "  Tables are available at this time");

                    } else {
                        lblCurrentSituationTable.setText(" Tables are not available at this time");
                    }
                }
            } else if (optTableBselect.isSelected()) {
                String sql = "SELECT count(tableB) FROM customermanager WHERE date = ? AND timeSlotNo = ? AND tableB = ? ";
                pst = conn.prepareStatement(sql);
                pst.setString(1, searchDate);
                pst.setInt(2, timeNo);
                pst.setString(3, "y");
                ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    bookedFinishedTablecount = rs.getInt("count(tableB)");
                    if (bookedFinishedTablecount < view.countTableB) {
                        remainingTables = view.countTableB - bookedFinishedTablecount;

                        lblCurrentSituationTable.setText(String.valueOf(remainingTables) + "  Tables are available at this time");

                    } else {
                        lblCurrentSituationTable.setText(" Tables are not available at this time");
                    }
                }
            }
         }
        } 
       }catch(Exception e){
           System.out.println(e);
       }
    }//GEN-LAST:event_cmdSearchActionPerformed

