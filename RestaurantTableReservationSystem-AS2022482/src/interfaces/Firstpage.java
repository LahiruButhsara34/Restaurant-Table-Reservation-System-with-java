    private void registration(){
        String uname=txtUsername.getText();
        String password=txtPassword.getText();//password column size is 10
        String email;
              if(txtEmail.getText().equals("Enter Email..." ) ){
                       email="";
               } 
               else{
                       email=txtEmail.getText();
               }
              String contact=txtContact.getText(); 
              
            try {  
                String query = "INSERT INTO users (username,password,email,contact) VALUES (?,?,?,?)";
                pst = conn.prepareStatement(query);    
                pst.setString(1, uname);
                pst.setString(2, password);
                pst.setString(3, email);
                pst.setString(4, contact);
                pst.execute();    
                JOptionPane.showMessageDialog(this, "Registration Successfuly");    
            } 
           catch (Exception e) {
                 JOptionPane.showMessageDialog(null, "Try Again");
            }     
    }
    
   
